import ts from 'typescript';
import { writeFileSync } from 'node:fs';

const config = ts.readConfigFile('tsconfig.json', ts.sys.readFile);
const { fileNames, options } = ts.parseJsonConfigFileContent(config.config, ts.sys, '.');
const program = ts.createProgram(fileNames, options);
const checker = program.getTypeChecker();
const entry = program.getSourceFile('index.tsx');
const result = {};

for (const exported of checker.getExportsOfModule(checker.getSymbolAtLocation(entry))) {
  const name = exported.name;
  if (!/^[A-Z]/.test(name)) continue;
  const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
  const node = symbol.valueDeclaration;
  if (!node) continue;
  const signatures = checker.getSignaturesOfType(checker.getTypeOfSymbolAtLocation(symbol, node), ts.SignatureKind.Call);
  if (!signatures.length) continue;
  result[name] = signatures.map(signature => {
    const parameter = signature.parameters[0];
    if (!parameter) return [];
    const type = checker.getTypeOfSymbolAtLocation(parameter, node);
    return checker.getPropertiesOfType(type).map(prop => {
      const optional = Boolean(prop.flags & ts.SymbolFlags.Optional);
      const type = checker.getTypeOfSymbolAtLocation(prop, node);
      const display = checker.typeToString(type, node, ts.TypeFormatFlags.NoTruncation)
        .replace(/import\("[^"]+"\)\./g, '')
        .replace(/ \| undefined$/, '')
        .replace(/false \| true/g, 'boolean');
      return [prop.name, display, optional];
    });
  });
}
writeFileSync('docs/props.js', '// Generated by node tooling/build-doc-props.mjs\nconst jsxProps = ' + '{\n' + Object.entries(result).map(([name, signatures]) => '  ' + JSON.stringify(name) + ': ' + JSON.stringify(signatures)).join(',\n') + '\n}' + ';\n');
